"""Generate the ProofOps ontology (OWL) and evidence contracts (SHACL) from the benchmark taxonomy.

Ontology Pipeline stages, all in one place so they stay consistent:
  controlled vocabulary  -> one preferred label per fault class / root cause / signal kind
  taxonomy               -> Fault > 8 fault classes (benchmark fault_taxonomy) > 57 root causes
  thesaurus              -> skos:altLabel = the benchmark's own identifier (e.g. Admission_Fault)
  ontology               -> OWL classes, evidence types, defined classes per fault class
  contracts              -> SHACL: what evidence a diagnosis of each class must carry

Provenance: class names and the root-cause -> class mapping come from Cloud-OpsBench index.jsonl
(field fault_taxonomy / root_cause, Online Boutique). Definitions and evidence rules are ours.

Usage: .venv/bin/python scripts/build_ontology.py
"""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "data/raw/hf/index.jsonl"

CLASSES = {  # benchmark id -> (our class name, definition, allowed corroborating signal kinds)
    "Admission_Fault": ("AdmissionFault", "Kubernetes refuses to create pods (quota exceeded, missing service account).",
                        ["WarningEvent", "PodStatus", "LogError", "Alert"]),
    "Scheduling_Fault": ("SchedulingFault", "Pods are created but no node can run them (affinity, taints, capacity, volumes).",
                         ["WarningEvent", "PodStatus", "LogError", "Alert"]),
    "Startup_Fault": ("StartupFault", "Pods are scheduled but containers cannot start (image pull, secrets, mounts).",
                      ["WarningEvent", "PodStatus", "LogError", "Alert"]),
    "Runtime_Fault": ("RuntimeFault", "Containers start but are killed or restarted (probes, memory limits).",
                      ["WarningEvent", "PodStatus", "LogError", "Alert", "MetricAnomaly"]),
    "Service_Routing_Fault": ("ServiceRoutingFault", "Pods run but traffic cannot reach them (selector, port, protocol, address).",
                              ["LogError", "Alert", "MetricAnomaly", "WarningEvent"]),
    "Performance_Fault": ("PerformanceFault", "Everything runs but too slowly (CPU overload, network delay or loss).",
                          ["MetricAnomaly", "Alert", "LogError"]),
    "Infrastructure_Fault": ("InfrastructureFault", "A cluster component on a node fails (containerd, kubelet, kube-proxy, scheduler).",
                             ["WarningEvent", "PodStatus", "MetricAnomaly", "Alert", "LogError"]),
    "Application_Code_Defect": ("CodeDefect", "The application's own code misbehaves (wrong return, busy loop, leaks).",
                                ["LogError", "Alert", "MetricAnomaly"]),
}
SIGNAL_KINDS = {
    "WarningEvent": "A Kubernetes Warning event", "PodStatus": "An abnormal pod status or restarts",
    "LogError": "Error lines in application logs", "Alert": "A monitoring alert",
    "MetricAnomaly": "A metric deviating from its baseline", "State": "A configuration state read from kubectl",
}


def main():
    rows = [json.loads(l) for l in INDEX.open() if l.strip()]
    rc = defaultdict(set)
    for r in rows:
        if r["system"] == "boutique":
            rc[r["fault_taxonomy"]].add(r["root_cause"])

    o = ["@prefix po:   <https://example.org/proofops#> .", "@prefix owl:  <http://www.w3.org/2002/07/owl#> .",
         "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .", "@prefix skos: <http://www.w3.org/2004/02/skos/core#> .",
         "@prefix prov: <http://www.w3.org/ns/prov#> .", "",
         "<https://example.org/proofops> a owl:Ontology ; rdfs:label \"ProofOps ontology\" ;",
         "    rdfs:comment \"Generated by scripts/build_ontology.py from Cloud-OpsBench fault_taxonomy/root_cause (Online Boutique).\" .",
         "skos:prefLabel a owl:AnnotationProperty . skos:altLabel a owl:AnnotationProperty . skos:definition a owl:AnnotationProperty .",
         "", "### Taxonomy: Fault > fault class > root cause",
         "po:Fault a owl:Class ; skos:prefLabel \"Fault\" ; skos:definition \"A condition that causes user-visible symptoms.\" ."]
    n_rc = 0
    for bid, (cls, defn, _) in CLASSES.items():
        o.append(f"po:{cls} a owl:Class ; rdfs:subClassOf po:Fault ; skos:prefLabel \"{cls}\" ; "
                 f"skos:altLabel \"{bid}\" ; skos:definition \"{defn}\" .")
        for r in sorted(rc.get(bid, [])):
            n_rc += 1
            label = r.replace("_", " ")
            o.append(f"po:rc_{r} a owl:Class ; rdfs:subClassOf po:{cls} ; skos:prefLabel \"{label}\" ; skos:altLabel \"{r}\" .")
    o += ["", "### Evidence, signals, diagnoses",
          "po:Evidence a owl:Class ; rdfs:subClassOf prov:Entity .",
          "po:TemporalPrecedence a owl:Class ; rdfs:subClassOf po:Evidence ; skos:definition \"Cause state existed no later than the first symptom, within a stated tolerance.\" .",
          "po:DependencyPath a owl:Class ; rdfs:subClassOf po:Evidence ; skos:definition \"A path of calls links a symptomatic service to the affected component.\" .",
          "po:CorroboratingSignal a owl:Class ; rdfs:subClassOf po:Evidence ; skos:definition \"A signal of a different kind than the cause agrees.\" .",
          "po:SignalKind a owl:Class ."]
    for k, d in SIGNAL_KINDS.items():
        o.append(f"po:{k} a owl:NamedIndividual , po:SignalKind ; skos:definition \"{d}\" .")
    o += ["po:Diagnosis a owl:Class .", "po:hasEvidence a owl:ObjectProperty ; rdfs:domain po:Diagnosis ; rdfs:range po:Evidence .",
          "po:diagnosedFault a owl:ObjectProperty ; rdfs:domain po:Diagnosis ; rdfs:range po:Fault .",
          "po:signalKind a owl:ObjectProperty ; rdfs:range po:SignalKind .",
          "po:dependsOn a owl:ObjectProperty , owl:TransitiveProperty ; skos:definition \"Service call dependency; transitive, which yields multi-hop paths.\" .",
          "", "### Defined classes: the reasoner classifies a diagnosis by its fault class (and so its contract)"]
    for bid, (cls, _, _) in CLASSES.items():
        o.append(f"po:{cls}Diagnosis a owl:Class ; owl:equivalentClass [ a owl:Class ; owl:intersectionOf ( po:Diagnosis "
                 f"[ a owl:Restriction ; owl:onProperty po:diagnosedFault ; owl:someValuesFrom po:{cls} ] ) ] .")
    o += ["", "### Demo individuals for Protege (start HermiT; dx_C06 is inferred to be an AdmissionFaultDiagnosis)",
          "po:fault_C06 a owl:NamedIndividual , po:rc_missing_service_account .",
          "po:dx_C06 a owl:NamedIndividual , po:Diagnosis ; po:diagnosedFault po:fault_C06 ."]
    (ROOT / "ontology/proofops.ttl").write_text("\n".join(o) + "\n")

    s = ["@prefix sh:   <http://www.w3.org/ns/shacl#> .", "@prefix po:   <https://example.org/proofops#> .",
         "@prefix prov: <http://www.w3.org/ns/prov#> .", "",
         "# Base contract on every diagnosis (inherited by all fault classes). Checked closed-world on ONE incident",
         "# snapshot, which is what lets us report evidence as MISSING rather than merely unknown.",
         "po:DiagnosisContract a sh:NodeShape ; sh:targetClass po:Diagnosis ;"]
    for ev in ("TemporalPrecedence", "DependencyPath", "CorroboratingSignal"):
        s.append(f"  sh:property [ sh:path po:hasEvidence ; sh:qualifiedValueShape [ sh:class po:{ev} ] ; "
                 f"sh:qualifiedMinCount 1 ; sh:message \"Missing evidence: {ev}\" ] ;")
    s[-1] = s[-1].rstrip(" ;") + " ."
    s += ["", "po:EvidenceProvenance a sh:NodeShape ; sh:targetClass po:Evidence ;",
          "  sh:property [ sh:path prov:wasDerivedFrom ; sh:minCount 1 ; sh:message \"Evidence without provenance\" ] .", "",
          "# Class-specific contracts: which signal kinds may corroborate a diagnosis of that class."]
    for bid, (cls, _, kinds) in CLASSES.items():
        s.append(f"po:{cls}Contract a sh:NodeShape ; sh:targetClass po:{cls}Diagnosis ;")
        s.append(f"  sh:property [ sh:path ( po:hasEvidence po:signalKind ) ; sh:in ( {' '.join('po:' + k for k in kinds)} ) ; "
                 f"sh:message \"Corroborating signal kind not allowed for {cls}\" ] .")
    (ROOT / "contracts/contracts.shacl.ttl").write_text("\n".join(s) + "\n")
    print(f"ontology: 8 fault classes, {n_rc} root causes -> ontology/proofops.ttl")
    print("contracts: base + 8 class contracts -> contracts/contracts.shacl.ttl")


if __name__ == "__main__":
    main()
